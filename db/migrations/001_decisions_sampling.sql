-- 001: agent decisions and human-approved sampling tasks.
-- Additive only and safe to re-run: guarded types, IF NOT EXISTS tables/indexes, guarded seed.

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'agent_action') THEN
        CREATE TYPE agent_action AS ENUM (
            'mark_artifact', 'log_expected', 'schedule_recheck', 'create_sampling_task'
        );
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'sampling_status') THEN
        CREATE TYPE sampling_status AS ENUM ('pending_approval', 'approved', 'rejected', 'done');
    END IF;
END
$$;

CREATE TABLE IF NOT EXISTS agent_decision (
    decision_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id    BIGINT NOT NULL REFERENCES plume_event(event_id) ON DELETE CASCADE,
    action      agent_action NOT NULL,
    reason      TEXT NOT NULL,
    trace       JSONB,
    model_id    TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_decision_event ON agent_decision (event_id, created_at DESC);

CREATE TABLE IF NOT EXISTS sampling_task (
    task_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id         BIGINT NOT NULL REFERENCES plume_event(event_id) ON DELETE CASCADE,
    decision_id      BIGINT REFERENCES agent_decision(decision_id) ON DELETE SET NULL,
    status           sampling_status NOT NULL DEFAULT 'pending_approval',
    sites            JSONB,
    requested_reason TEXT,
    reviewed_by      TEXT,
    review_note      TEXT,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    reviewed_at      TIMESTAMPTZ,
    CONSTRAINT ck_sampling_task_reviewed CHECK (
        status = 'pending_approval' OR (reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL)
    )
);
CREATE INDEX IF NOT EXISTS ix_sampling_task_event ON sampling_task (event_id);
CREATE INDEX IF NOT EXISTS ix_sampling_task_status ON sampling_task (status);

-- Seed: one pending task for the Binangonan 2026-05-06 dry-weather plume (looked up, not hardcoded).
INSERT INTO sampling_task (event_id, status, sites, requested_reason)
SELECT e.event_id,
       'pending_approval',
       jsonb_build_array(
           jsonb_build_object('label', 'entry_point',
                              'lon', ST_X(e.entry_geom), 'lat', ST_Y(e.entry_geom)),
           jsonb_build_object('label', 'plume_centroid',
                              'lon', ST_X(e.centroid_geom), 'lat', ST_Y(e.centroid_geom))
       ),
       'Suspicious, verify: dry-weather plume seen in Sentinel-2 imagery at the Binangonan '
       || 'shoreline on 2026-05-06 with little recent rain. Satellites show water colour '
       || 'change only, not specific pollutants; field samples are needed to confirm.'
FROM v_dry_weather_plumes d
JOIN plume_event e ON e.event_id = d.event_id
WHERE d.place ILIKE 'Binangonan%'
  AND d.acquired_date = DATE '2026-05-06'
  AND NOT EXISTS (SELECT 1 FROM sampling_task t WHERE t.event_id = d.event_id)
ORDER BY d.area_ha DESC
LIMIT 1;
