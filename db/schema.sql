-- Lawata: satellite water-quality monitoring database
-- Target: PostgreSQL 15+ with PostGIS 3 (works on Neon)
-- Conventions: snake_case; BIGINT identity keys; timestamptz in UTC; DATE for local (Asia/Manila) days;
-- geometries in WGS84 (EPSG:4326); areas in hectares; rainfall in mm.

CREATE EXTENSION IF NOT EXISTS postgis;

BEGIN;

-- ---------- reference ----------
CREATE TABLE aoi (
    aoi_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        TEXT NOT NULL UNIQUE CHECK (code ~ '^[a-z0-9_]+$'),
    name        TEXT NOT NULL,
    geom        geometry(Polygon, 4326) NOT NULL,
    grid_crs    TEXT,
    grid_res_m  NUMERIC(6,2) CHECK (grid_res_m > 0),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE satellite_tile (
    tile_code   TEXT PRIMARY KEY CHECK (tile_code ~ '^[0-9]{2}[A-Z]{3}$'),
    footprint   geometry(Polygon, 4326)
);

CREATE TABLE platform (
    platform_code TEXT PRIMARY KEY,
    mission       TEXT NOT NULL
);

CREATE TABLE scene (
    scene_id        TEXT PRIMARY KEY,
    platform_code   TEXT NOT NULL REFERENCES platform(platform_code),
    tile_code       TEXT NOT NULL REFERENCES satellite_tile(tile_code),
    acquired_at     TIMESTAMPTZ NOT NULL,
    acquired_date   DATE NOT NULL,
    tile_cloud_pct  NUMERIC(5,2) CHECK (tile_cloud_pct BETWEEN 0 AND 100),
    stac_collection TEXT NOT NULL DEFAULT 'sentinel-2-l2a',
    stac_endpoint   TEXT NOT NULL DEFAULT 'https://earth-search.aws.element84.com/v1'
);
CREATE INDEX ix_scene_date ON scene (acquired_date);
CREATE INDEX ix_scene_tile ON scene (tile_code);

CREATE TABLE acquisition (
    acquisition_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aoi_id           BIGINT NOT NULL REFERENCES aoi(aoi_id) ON DELETE CASCADE,
    acquired_date    DATE NOT NULL,
    water_clear_frac NUMERIC(5,4) CHECK (water_clear_frac BETWEEN 0 AND 1),
    usable_frac      NUMERIC(5,4) CHECK (usable_frac BETWEEN 0 AND 1),
    is_usable        BOOLEAN NOT NULL DEFAULT false,
    UNIQUE (aoi_id, acquired_date)
);

CREATE TABLE acquisition_scene (
    acquisition_id BIGINT NOT NULL REFERENCES acquisition(acquisition_id) ON DELETE CASCADE,
    scene_id       TEXT   NOT NULL REFERENCES scene(scene_id),
    PRIMARY KEY (acquisition_id, scene_id)
);
CREATE INDEX ix_acqscene_scene ON acquisition_scene (scene_id);

-- ---------- rasters (stored outside the DB, e.g. S3) ----------
CREATE TABLE raster_product (
    product_code TEXT PRIMARY KEY,
    description  TEXT NOT NULL,
    bands        TEXT[],
    dtype        TEXT NOT NULL,
    scale_factor DOUBLE PRECISION NOT NULL DEFAULT 1,
    nodata       DOUBLE PRECISION
);

CREATE TABLE raster_asset (
    asset_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_code   TEXT   NOT NULL REFERENCES raster_product(product_code),
    acquisition_id BIGINT REFERENCES acquisition(acquisition_id) ON DELETE CASCADE,  -- NULL for static layers
    aoi_id         BIGINT NOT NULL REFERENCES aoi(aoi_id) ON DELETE CASCADE,
    storage_uri    TEXT   NOT NULL UNIQUE,
    format         TEXT   NOT NULL DEFAULT 'COG',
    width          INTEGER CHECK (width > 0),
    height         INTEGER CHECK (height > 0),
    bytes          BIGINT  CHECK (bytes >= 0),
    sha256         TEXT    CHECK (sha256 IS NULL OR sha256 ~ '^[0-9a-f]{64}$'),
    status         TEXT    NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','stored','failed')),
    stored_at      TIMESTAMPTZ
);
CREATE INDEX ix_raster_acq ON raster_asset (acquisition_id);
CREATE INDEX ix_raster_aoi_product ON raster_asset (aoi_id, product_code);

-- ---------- weather ----------
CREATE TABLE weather_source (
    source_code TEXT PRIMARY KEY,
    name        TEXT NOT NULL,
    url         TEXT NOT NULL,
    notes       TEXT
);

CREATE TABLE rain_station (
    station_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_code TEXT NOT NULL REFERENCES weather_source(source_code),
    geom        geometry(Point, 4326) NOT NULL,
    UNIQUE (source_code, geom)
);
CREATE INDEX ix_station_geom ON rain_station USING gist (geom);

CREATE TABLE rainfall_daily (
    station_id BIGINT NOT NULL REFERENCES rain_station(station_id) ON DELETE CASCADE,
    obs_date   DATE   NOT NULL,
    precip_mm  REAL   CHECK (precip_mm IS NULL OR precip_mm >= 0),
    PRIMARY KEY (station_id, obs_date)
);

-- ---------- places ----------
CREATE TABLE place (
    place_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            TEXT NOT NULL,
    province        TEXT,
    geom            geometry(Point, 4326) NOT NULL,
    rain_station_id BIGINT REFERENCES rain_station(station_id),
    notes           TEXT,
    UNIQUE (name, province, geom)
);
CREATE INDEX ix_place_geom ON place USING gist (geom);

-- ---------- detection ----------
CREATE TABLE detection_run (
    run_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aoi_id       BIGINT NOT NULL REFERENCES aoi(aoi_id) ON DELETE CASCADE,
    method       TEXT   NOT NULL,
    code_version TEXT   NOT NULL,
    params       JSONB  NOT NULL,
    started_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    notes        TEXT
);

CREATE TABLE plume_kind (
    kind_code   TEXT PRIMARY KEY,
    description TEXT NOT NULL
);

CREATE TABLE plume_event (
    event_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id          BIGINT NOT NULL REFERENCES detection_run(run_id) ON DELETE CASCADE,
    acquisition_id  BIGINT NOT NULL REFERENCES acquisition(acquisition_id) ON DELETE CASCADE,
    place_id        BIGINT REFERENCES place(place_id),
    kind_code       TEXT   NOT NULL REFERENCES plume_kind(kind_code),
    area_ha         NUMERIC(10,2) NOT NULL CHECK (area_ha > 0),
    change_score    REAL NOT NULL,
    roughness_ratio REAL,
    entry_geom      geometry(Point, 4326) NOT NULL,      -- where the plume touches the shore
    centroid_geom   geometry(Point, 4326) NOT NULL,
    bbox_px         JSONB
);
CREATE INDEX ix_event_acq   ON plume_event (acquisition_id);
CREATE INDEX ix_event_place ON plume_event (place_id);
CREATE INDEX ix_event_run   ON plume_event (run_id);
CREATE INDEX ix_event_entry ON plume_event USING gist (entry_geom);

CREATE TABLE event_review (
    review_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id    BIGINT NOT NULL REFERENCES plume_event(event_id) ON DELETE CASCADE,
    verdict     TEXT   NOT NULL CHECK (verdict IN ('confirmed','artifact','uncertain')),
    reason      TEXT,
    reviewer    TEXT   NOT NULL,
    reviewed_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_review_event ON event_review (event_id, reviewed_at DESC);

CREATE TABLE watch_zone (
    zone_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aoi_id   BIGINT NOT NULL REFERENCES aoi(aoi_id) ON DELETE CASCADE,
    place_id BIGINT REFERENCES place(place_id),
    name     TEXT NOT NULL UNIQUE,
    geom     geometry(Polygon, 4326) NOT NULL
);
CREATE INDEX ix_zone_geom ON watch_zone USING gist (geom);

CREATE TABLE zone_observation (
    zone_id       BIGINT NOT NULL REFERENCES watch_zone(zone_id) ON DELETE CASCADE,
    run_id        BIGINT NOT NULL REFERENCES detection_run(run_id) ON DELETE CASCADE,
    acquired_date DATE   NOT NULL,
    anomaly_pct   REAL   CHECK (anomaly_pct BETWEEN 0 AND 100),
    PRIMARY KEY (zone_id, run_id, acquired_date)
);

-- ---------- external events ----------
CREATE TABLE source_document (
    doc_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    outlet    TEXT NOT NULL,
    title     TEXT NOT NULL,
    url       TEXT NOT NULL UNIQUE,
    published DATE
);

CREATE TABLE incident_type (
    type_code   TEXT PRIMARY KEY,
    description TEXT NOT NULL
);

CREATE TABLE incident (
    incident_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_code   TEXT NOT NULL REFERENCES incident_type(type_code),
    occurred_on DATE,
    place_id    BIGINT REFERENCES place(place_id),
    summary     TEXT NOT NULL,
    doc_id      BIGINT REFERENCES source_document(doc_id)
);
CREATE INDEX ix_incident_place ON incident (place_id);

-- ---------- views ----------
CREATE VIEW v_event_latest_review AS
SELECT DISTINCT ON (event_id) *
FROM event_review
ORDER BY event_id, reviewed_at DESC, review_id DESC;

-- Each plume with rainfall at its place's station: prior 3 and 7 days, acquisition day included
CREATE VIEW v_plume_event_context AS
SELECT e.event_id, e.run_id, a.aoi_id, a.acquired_date,
       p.name AS place, p.province, e.kind_code, e.area_ha, e.change_score,
       ST_Y(e.entry_geom) AS entry_lat, ST_X(e.entry_geom) AS entry_lon,
       r3.mm AS rain_3d_mm, r7.mm AS rain_7d_mm,
       COALESCE(lr.verdict, 'uncertain') AS verdict,
       e.entry_geom
FROM plume_event e
JOIN acquisition a ON a.acquisition_id = e.acquisition_id
LEFT JOIN place p ON p.place_id = e.place_id
LEFT JOIN v_event_latest_review lr ON lr.event_id = e.event_id
LEFT JOIN LATERAL (SELECT SUM(precip_mm) AS mm FROM rainfall_daily rd
                   WHERE rd.station_id = p.rain_station_id
                     AND rd.obs_date BETWEEN a.acquired_date - 3 AND a.acquired_date) r3 ON true
LEFT JOIN LATERAL (SELECT SUM(precip_mm) AS mm FROM rainfall_daily rd
                   WHERE rd.station_id = p.rain_station_id
                     AND rd.obs_date BETWEEN a.acquired_date - 7 AND a.acquired_date) r7 ON true;

CREATE VIEW v_dry_weather_plumes AS
SELECT * FROM v_plume_event_context
WHERE verdict <> 'artifact' AND rain_3d_mm < 5 AND rain_7d_mm < 15;

COMMIT;
